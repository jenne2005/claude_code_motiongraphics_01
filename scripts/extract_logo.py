"""Turn the Illustrator-exported logo SVG into layered path data for the canvas renderer.

Usage: python3 scripts/extract_logo.py assets/brand/logo-orange.svg src/logo-data.js

The export (pdftocairo -svg of page 1 of the brand PDF) keeps every logo element as
its own path, in a stable stacking order. We name each one so the animation can
move the flame, frame, stripes and every letter of the wordmark independently.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET

NS = {"svg": "http://www.w3.org/2000/svg", "xlink": "http://www.w3.org/1999/xlink"}
XLINK_HREF = "{http://www.w3.org/1999/xlink}href"

# Body paths in document order (after the background rect).
NAMES = (
    ["frameBottom", "frameTopLeft", "frameTopRight"]
    + ["stripesBottom", "stripesTopRight", "stripesTopLeft"]
    + ["star"]
    + [f"letterShadow{i}" for i in range(9)]
    + [f"letterOutline{i}" for i in range(9)]
    + [f"letterFace{i}" for i in range(9)]
    + ["flameBody"]
    + [f"flameLick{i}" for i in range(4)]
)

COLORS = {
    "rgb(100%, 100%, 100%)": "white",
    "rgb(100%, 94.898987%, 0%)": "yellow",
    "rgb(2.69928%, 2.69928%, 2.69928%)": "black",
    "rgb(94.499207%, 35.299683%, 16.099548%)": "orange",
}


def compact(d):
    """Round coordinates to 3 decimals to keep the data file small."""
    return re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.3f}".rstrip("0").rstrip("."), " ".join(d.split()))


def bbox(d):
    """Bounding box from all path coordinates (control points included; close enough for pivots)."""
    nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", d)]
    xs, ys = nums[0::2], nums[1::2]
    return [round(min(xs), 2), round(min(ys), 2), round(max(xs), 2), round(max(ys), 2)]


def main(src, dst):
    root = ET.parse(src).getroot()
    glyphs = {}
    for g in root.iter("{http://www.w3.org/2000/svg}g"):
        gid = g.get("id")
        if gid and gid.startswith("glyph-"):
            p = g.find("svg:path", NS)
            glyphs[gid] = compact(p.get("d")) if p is not None and p.get("d") else ""

    body = [el for el in root if not el.tag.endswith("defs")]
    paths = [el for el in body if el.tag.endswith("path")]
    assert len(paths) == len(NAMES), f"expected {len(NAMES)} paths, got {len(paths)}"

    layers = []
    for name, p in zip(NAMES, paths):
        d = compact(p.get("d"))
        layers.append({"name": name, "fill": COLORS[p.get("fill")], "d": d, "bbox": bbox(d)})

    texts = {"tagline": [], "estd": [], "year": []}
    for g in body:
        if not g.tag.endswith("g"):
            continue
        for u in g.findall("svg:use", NS):
            x, y = float(u.get("x")), float(u.get("y"))
            key = "tagline" if y > 120 else ("estd" if x < 150 else "year")
            texts[key].append({"g": u.get(XLINK_HREF)[1:], "x": round(x, 3), "y": round(y, 3)})

    used = {u["g"] for t in texts.values() for u in t}
    data = {
        "viewBox": [288, 216],
        "layers": layers,
        "glyphs": {k: v for k, v in glyphs.items() if k in used},
        "texts": texts,
    }
    with open(dst, "w") as f:
        f.write("// Generated by scripts/extract_logo.py from the official brand PDF. Do not edit.\n")
        f.write("window.LOGO = " + json.dumps(data, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
